"""Read best params from logs/hyperopt_<S>.log (--print-json line) and write user_data/strategies/xau_tuned.py
with <S>_T subclasses carrying buy/sell/protection params. Only in-sample (08-20..10-20) hyperopt results are used."""
import json, re, sys, glob
from pathlib import Path
out = ['"""Auto-generated by make_tuned.py: in-sample-tuned parameter sets (2026-08-20..2026-10-20)."""',
       'from xau_families import XauZone, XauS2, XauS3, XauPullback, XauORB, XauVWAP, XauMR', '']
best = {}
for f in sorted(glob.glob('logs/hyperopt_*.log')):
    s = Path(f).stem.replace('hyperopt_', '')
    js = [l for l in open(f).read().splitlines() if l.startswith('{"params"')]
    if not js:
        continue
    j = json.loads(js[-1]); best[s] = j
    import importlib.util, sys as _s
    _s.path.insert(0, 'user_data/strategies')
    import xau_families as xf
    cls = getattr(xf, s)
    buy, sell = {}, {}
    for k, v in j['params'].items():
        (buy if getattr(cls, k).space == 'buy' else sell)[k] = v
    prot = {k: j[k] for k in ('cooldown', 'slg_limit') if k in j}
    out += [f'class {s}_T({s}):', f'    buy_params = {buy!r}', f'    sell_params = {sell!r}', f'    protection_params = {prot!r}', '']
open('user_data/strategies/xau_tuned.py', 'w').write('\n'.join(out))
json.dump(best, open('best_params_is.json', 'w'), indent=1)
print('\n'.join(out))
